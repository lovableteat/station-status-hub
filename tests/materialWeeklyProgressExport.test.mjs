import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFile } from "node:fs/promises";
import test from "node:test";
import ts from "typescript";
import ExcelJS from "exceljs";
import { buildMaterialWeeklyProgress, getMaterialProgressWeeks } from "../src/components/material-requests/materialWeeklyProgress.ts";
const native = createRequire(import.meta.url);
const { loader } = native("./support/renderHarness.cjs");

test("weekly workbook round-trips all filtered rows, chronological snapshots, full updates and text part numbers", async () => {
  const load = loader();
  const source = await readFile("src/components/material-requests/materialWeeklyProgressExport.ts", "utf8");
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const exports = {};
  new Function("require", "exports", compiled)(name => name.startsWith(".") ? load("src/components/material-requests/" + name.slice(2) + ".ts") : native(name), exports);
  const asOf = Date.parse("2026-11-02T04:00:00Z");
  const weeks = getMaterialProgressWeeks("2026-11-02", 4, asOf);
  const record = { id: "J1", refDes: Array.from({ length: 80 }, (_, i) => `J${i + 1}`).join(", "), name: "完整料件名稱", qty: 0, manufacturerPartNumber: "00001234", manufacturer: "Vendor A", partNumber: "000-REAL", requestOwnerName: "指派 CE", note: "網站 Note", trackingHistory: [{ id: "a", status: "已發信", createdAt: "2026-10-25T16:00:00Z", createdBy: "真正操作者", requestInfo: "已聯繫", note: "完整\n追蹤說明", requestTicket: "000-TICKET", requestUrl: "https://example.invalid/request" }, { id: "b", status: "已取得料號待CIS申請", createdAt: "2026-11-02T03:00:00Z", createdBy: "CE" }] };
  const records = Array.from({ length: 61 }, (_, i) => ({ ...record, id: String(i) }));
  const rows = buildMaterialWeeklyProgress(records, weeks, asOf);
  const workbook = await exports.createMaterialWeeklyWorkbook({ rows, weeks, asOf, workspaceName: "BOM A", exportedBy: "QA", scope: "全部料件 · 負責人：指派 CE" });
  const reopened = new ExcelJS.Workbook();
  await reopened.xlsx.load(await workbook.xlsx.writeBuffer());
  const matrix = reopened.getWorksheet("各料每週進度");
  assert.equal(matrix.rowCount, 65, "export never limits itself to the UI page of 50 records");
  const headers = matrix.getRow(4).values;
  const value = label => matrix.getRow(5).getCell(headers.indexOf(label)).value;
  assert.equal(value("Ref Des"), record.refDes);
  assert.equal(value("Manufacturer Part Number"), "00001234");
  assert.equal(value("實體料號"), "000-REAL");
  assert.equal(value("Qty"), 0);
  assert.equal(value("負責人（目前）"), "指派 CE");
  assert.equal(value("Note"), "網站 Note");
  assert.equal(value(weeks[3].label + "（本週）"), "已取得料號待CIS申請");
  assert.equal(value(weeks[2].label), "已發信");
  assert.equal(matrix.getRow(4).font.bold, true);
  assert.equal(matrix.getRow(5).getCell(headers.indexOf("Manufacturer Part Number")).numFmt, "@");
  assert.equal(matrix.views[0].ySplit, 4);
  const updates = reopened.getWorksheet("週內更新明細");
  assert.equal(updates.rowCount, 126);
  assert.equal(updates.getCell("G5").value, "真正操作者");
  assert.equal(updates.getCell("I5").value, "完整\n追蹤說明");
  assert.equal(updates.getCell("J5").value, "000-TICKET");
  const summary = reopened.getWorksheet("每週彙總");
  const summaryHeaders = summary.getRow(4).values;
  assert.equal(summary.getRow(5).getCell(summaryHeaders.indexOf("已取得料號待CIS申請")).value, 61);
  assert.match(matrix.getCell("A2").value, /負責人：指派 CE/);
});
