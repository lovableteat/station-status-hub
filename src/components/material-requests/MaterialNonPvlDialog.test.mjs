import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import test from 'node:test';
const require = createRequire(import.meta.url);
const { React, create, act, loader } = require('../../../tests/support/renderHarness.cjs');

test('PLM rejection review excludes matched physical numbers only, including duplicate rows, and supports reselecting', () => {
  const { MaterialNonPvlDialog } = loader()('src/components/material-requests/MaterialNonPvlDialog.tsx');
  const rows = ['1A20-0000100', '1A20-0000100', '1022-00001ZZ', ''].map((partNumber, index) => ({ refDes: 'R' + index, name: 'RES', manufacturer: 'Example', manufacturerPartNumber: 'MPN', partNumber, virtualAlternative: '', partUsageStatus: '不建議使用' }));
  const original = structuredClone(rows);
  const exports = [];
  let view;
  act(() => { view = create(React.createElement(MaterialNonPvlDialog, { open: true, isExporting: false, rows, workspaceName: 'QA', onOpenChange() {}, onExportDetail() {}, onExportApplyList: parts => exports.push(parts) })); });
  const node = props => view.root.findAllByProps(props).find(item => item.type === 'stub');
  const button = label => view.root.find(item => item.type === 'stub' && item.props.children === label);
  act(() => node({ 'aria-label': 'PLM 退件訊息' }).props.onChange({ target: { value: '1A20-0000100: 已有此設定\n9999-00000ZZ: 未知' } }));
  act(() => button('比對退件料號').props.onClick());
  assert.match(JSON.stringify(view.toJSON()), /9999-00000ZZ/);
  assert.match(JSON.stringify(view.toJSON()), /精確匹配/);
  const exclude = view.root.find(item => item.type === 'stub' && Array.isArray(item.props.children) && item.props.children[0] === '排除已匹配的 ');
  act(() => exclude.props.onClick());
  const checkboxes = view.root.findAll(item => item.type === 'stub' && item.props['aria-label']?.startsWith('匯出料號'));
  assert.equal(checkboxes[0].props.checked, false);
  assert.equal(checkboxes[1].props.checked, false);
  assert.equal(checkboxes[3].props.disabled, true);
  act(() => node({ 'data-testid': 'non-pvl-export-apply' }).props.onClick());
  assert.deepEqual([...exports[0]], ['1022-00001ZZ']);
  act(() => button('全部選取').props.onClick());
  act(() => node({ 'data-testid': 'non-pvl-export-apply' }).props.onClick());
  assert.deepEqual([...exports[1]], ['1A20-0000100', '1022-00001ZZ']);
  act(() => node({ 'aria-label': '搜尋不建議料' }).props.onChange({ target: { value: '1022-00001ZZ' } }));
  act(() => button('排除搜尋結果').props.onClick());
  act(() => node({ 'aria-label': '清除不建議料搜尋條件' }).props.onClick());
  act(() => node({ 'data-testid': 'non-pvl-export-apply' }).props.onClick());
  assert.deepEqual([...exports[2]], ['1A20-0000100']);
  act(() => button('排除搜尋結果').props.onClick());
  assert.equal(node({ 'data-testid': 'non-pvl-export-apply' }).props.disabled, true);
  assert.deepEqual(rows, original);
  act(() => view.unmount());
});
